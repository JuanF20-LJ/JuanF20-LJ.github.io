-- 4. ¿La cuenta está verificada? (tiene algún código de verificación usado)
CREATE OR REPLACE FUNCTION pkg_usuaria.fn_esta_verificada(p_id_usuario INTEGER)
RETURNS BOOLEAN AS $$
BEGIN
    RETURN EXISTS (SELECT 1
                     FROM codigo_verificacion
                    WHERE usuaria_idusuario = p_id_usuario
                      AND usado = TRUE);
END;
$$ LANGUAGE plpgsql;

-- 5. Trigger al insertar un código: calcula la clave parcial (1, 2, 3... por usuaria)
--    y deja sin vigencia los códigos anteriores de esa usuaria.
CREATE OR REPLACE FUNCTION pkg_usuaria.fn_tg_codigo_nuevo()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.idcodigo IS NULL THEN
        SELECT COALESCE(MAX(idcodigo), 0) + 1 INTO NEW.idcodigo
          FROM codigo_verificacion
         WHERE usuaria_idusuario = NEW.usuaria_idusuario;
    END IF;
    UPDATE codigo_verificacion
       SET vigente = FALSE
     WHERE usuaria_idusuario = NEW.usuaria_idusuario
       AND vigente = TRUE;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS tg_codigo_verificacion_nuevo ON codigo_verificacion;
CREATE TRIGGER tg_codigo_verificacion_nuevo
BEFORE INSERT ON codigo_verificacion
FOR EACH ROW EXECUTE PROCEDURE pkg_usuaria.fn_tg_codigo_nuevo();

-- 6. Verifica un código: 1 correcto (lo marca usado), 2 incorrecto, 3 expirado, 4 no hay código vigente.
CREATE OR REPLACE FUNCTION pkg_usuaria.fn_verificar_codigo(p_id_usuario INTEGER, p_codigo VARCHAR)
RETURNS INTEGER AS $$
DECLARE
    v_codigo codigo_verificacion%ROWTYPE;
BEGIN
    SELECT * INTO v_codigo
      FROM codigo_verificacion
     WHERE usuaria_idusuario = p_id_usuario AND vigente = TRUE AND usado = FALSE
     ORDER BY fechageneracion DESC
     LIMIT 1;

    IF NOT FOUND THEN
        RETURN 4;
    END IF;
    IF v_codigo.fechaexpiracion < NOW() THEN
        RETURN 3;
    END IF;
    IF v_codigo.codigo <> p_codigo THEN
        RETURN 2;
    END IF;

    UPDATE codigo_verificacion
       SET usado = TRUE, vigente = FALSE
     WHERE idcodigo = v_codigo.idcodigo
       AND usuaria_idusuario = p_id_usuario;
    RETURN 1;
END;
$$ LANGUAGE plpgsql;

-- 7. Limpieza de códigos: borra los que nunca se usaron y vencieron hace más de 7 días.
--    (Sería un PROCEDURE en PostgreSQL 11+; en la 10 es una FUNCTION que devuelve cuántos borró.)
DROP FUNCTION IF EXISTS pkg_usuaria.sp_limpiar_codigos_expirados();
CREATE OR REPLACE FUNCTION pkg_usuaria.sp_limpiar_codigos_expirados()
RETURNS INTEGER AS $$
DECLARE
    v_borrados INTEGER;
BEGIN
    DELETE FROM codigo_verificacion
     WHERE usado = FALSE
       AND fechaexpiracion < NOW() - INTERVAL '7 days';
    GET DIAGNOSTICS v_borrados = ROW_COUNT;
    RETURN v_borrados;
END;
$$ LANGUAGE plpgsql;

-- 8. Promedios para predecir: duración de los últimos p_cantidad ciclos FINALIZADOS
--    y de las últimas p_cantidad menstruaciones confirmadas (con fecha de fin).
--    Se ignoran valores "raros" (ciclos fuera de 15-60 días, menstruaciones fuera de 1-15),
--    igual que lo hacía el backend. Devuelven el promedio redondeado (entero) o NULL si no hay datos.
DROP FUNCTION IF EXISTS pkg_ciclo.fn_duracion_promedio_ciclo(INTEGER, INTEGER);
CREATE OR REPLACE FUNCTION pkg_ciclo.fn_duracion_promedio_ciclo(p_id_usuario INTEGER, p_cantidad INTEGER DEFAULT 6)
RETURNS INTEGER AS $$
DECLARE
    v_promedio NUMERIC;
BEGIN
    SELECT AVG(t.duracion) INTO v_promedio
      FROM (SELECT (fechafin - fechainicio + 1) AS duracion
              FROM ciclo_menstrual
             WHERE usuaria_idusuario = p_id_usuario
               AND estado = 'FINALIZADO'
               AND fechafin IS NOT NULL
               AND (fechafin - fechainicio + 1) BETWEEN 15 AND 60
             ORDER BY fechainicio DESC
             LIMIT p_cantidad) t;
    RETURN ROUND(v_promedio);
END;
$$ LANGUAGE plpgsql;

DROP FUNCTION IF EXISTS pkg_ciclo.fn_duracion_promedio_menstruacion(INTEGER, INTEGER);
CREATE OR REPLACE FUNCTION pkg_ciclo.fn_duracion_promedio_menstruacion(p_id_usuario INTEGER, p_cantidad INTEGER DEFAULT 6)
RETURNS INTEGER AS $$
DECLARE
    v_promedio NUMERIC;
BEGIN
    SELECT AVG(t.duracion) INTO v_promedio
      FROM (SELECT (m.fechafin - m.fechainicio + 1) AS duracion
              FROM menstruacion m
              JOIN ciclo_menstrual c ON c.idciclomenstrual = m.ciclo_menstrual_idciclomenstrual
             WHERE c.usuaria_idusuario = p_id_usuario
               AND c.estado <> 'ESTIMADO'
               AND m.fechafin IS NOT NULL
               AND (m.fechafin - m.fechainicio + 1) BETWEEN 1 AND 15
             ORDER BY m.fechainicio DESC
             LIMIT p_cantidad) t;
    RETURN ROUND(v_promedio);
END;
$$ LANGUAGE plpgsql;

